# cmudict tables
# --------------------------------------------------------------------------

def gen_cmudict_tables():
    # Sorted so the C side can binary search, and so a diff of this file
    # after a mapping change shows the change rather than a reshuffle.
    pairs = sorted(cmudict.ARPABET_TO_SAM.items())
    for arp, sam in pairs:
        if not arp.isascii() or not sam.isascii():
            raise SystemExit('non-ASCII in ARPABET map: %r -> %r' % (arp, sam))

    stress = sorted(cmudict.CMU_TO_SAM_STRESS.items())
    if [k for k, _ in stress] != ['0', '1', '2']:
        raise SystemExit('unexpected stress keys: %r' % [k for k, _ in stress])

    h = [BANNER % ('sam_cmudict_tables.h', 'cmudict.py'), """
#ifndef SAM_CMUDICT_TABLES_H
#define SAM_CMUDICT_TABLES_H

#define SAM_ARPABET_COUNT %d

/* ARPABET base phoneme to the SAM spelling of the same sound. */
typedef struct {
    const char *arpabet;
    const char *sam;
} sam_arpabet_map_t;

/* Sorted by arpabet, so a binary search and Python's dict agree. */
extern const sam_arpabet_map_t sam_arpabet_map[SAM_ARPABET_COUNT];

/*
 * CMU stress digit to the SAM stress marker, indexed by digit - '0'.
 * "" for unstressed, "4" for primary, "2" for secondary.
 */
extern const char *const sam_stress_markers[3];

#endif /* SAM_CMUDICT_TABLES_H */
""" % len(pairs)]

    c = [BANNER % ('sam_cmudict_tables.c', 'cmudict.py'),
         '\n#include "sam_cmudict_tables.h"\n\n',
         'const sam_arpabet_map_t sam_arpabet_map[SAM_ARPABET_COUNT] = {\n']
    for arp, sam in pairs:
        c.append('    { %-6s %s },\n' % (cstr(arp) + ',', cstr(sam)))
    c.append('};\n\n')

    c.append('const char *const sam_stress_markers[3] = { %s };\n'
             % ', '.join(cstr(v) for _, v in stress))

    return ''.join(h), ''.join(c)


def write(name, text):
    path = os.path.join(OUT, name)
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d bytes)' % (path, len(text)))


def main():
    h, c = gen_parser_tables()
    write('sam_parser_tables.h', h)
    write('sam_parser_tables.c', c)

    h, c = gen_reciter_tables()
    write('sam_reciter_tables.h', h)
    write('sam_reciter_tables.c', c)

    h, c = gen_cmudict_tables()
    write('sam_cmudict_tables.h', h)
    write('sam_cmudict_tables.c', c)


if __name__ == '__main__':
    main()
